"""Worms' bodies (game/nethackvoxel/mods/nhv_tiles/worm_bodies.lua).

Worms are drawn with bodies behind their heads (nhv/worms.lua): a row of
the long worm tail's picture (its cell in nhv_tiles.png), facing you.
 * A long worm's tail, and the baby long worm's body: that picture as it is.
 * Other worms (purple worms, ...): that picture in the worm's own colours -
   the tail picture's body colour (its most common), the stripe along its
   back (the next) and its shading (its darkest) each turned into the
   worm's (read off the bottom rows of its picture: its body, not its
   eyes), written as textures/nhv_wormbody_<tile>.png.
Run it again after redrawing the tail or the worms.
"""
import os
import re
from collections import Counter

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
TILES = os.path.join(HERE, "..", "game", "nethackvoxel", "mods", "nhv_tiles")
SHEET = os.path.join(TILES, "textures", "nhv_tiles.png")
NAMES = os.path.join(TILES, "tilenames.lua")
OUT = os.path.join(TILES, "worm_bodies.lua")
TS = 16


def palette(cell, rows=None):
    """(body, accent, dark) of a picture: its most common colour, the
    next, its darkest (in the given rows only, if any)"""
    seen = Counter()
    for y in rows or range(TS):
        for x in range(TS):
            p = cell.getpixel((x, y))
            if p[3] >= 128:
                seen[p[:3]] += 1
    if not seen:
        return None
    dark = min(seen, key=lambda c: sum(c))
    lit = [c for c, _ in seen.most_common() if c != dark]
    body = lit[0] if lit else dark
    return body, lit[1] if len(lit) > 1 else body, dark


def main():
    src = open(NAMES, encoding="utf-8").read()
    cols = int(re.search(r"cols = (\d+)", src).group(1))

    def table(name):
        return src.split("\n  " + name + " = {", 1)[1].split("}", 1)[0]

    names = dict((int(k), v) for k, v in re.findall(r'\[(\d+)\] = "([^"]*)"', table("names")))
    sheet = dict((int(k), int(v)) for k, v in re.findall(r"\[(\d+)\] = (\d+)", table("sheet")))
    im = Image.open(SHEET).convert("RGBA")

    def cell(tile):
        s = sheet.get(tile, tile)
        x0, y0 = (s % cols) * TS, (s // cols) * TS
        return im.crop((x0, y0, x0 + TS, y0 + TS))

    # the tails: "long worm tail,male" -> {"long worm": {",male": tile}}
    tails = {}
    for tile, name in names.items():
        m = re.match(r"(.*) tail(,.*)?$", name)
        if m and not name.startswith("statue of"):
            tails.setdefault(m.group(1), {})[m.group(2) or ""] = tile
    out_tails, out_bodies = {}, {}
    for worm, by_sex in tails.items():
        for tile in by_sex.values():
            out_tails[tile] = ("tile", tile, names[tile])
    first_tail = min(t for by_sex in tails.values() for t in by_sex.values())
    from_pal = palette(cell(first_tail))
    for tile, name in names.items():
        m = re.match(r"(.*worm)(,.*)?$", name)
        if not m or name.startswith("statue of") or m.group(1) in tails:
            continue
        # (one of a worm with a tail: a baby long worm - its picture as it is)
        kin = [w for w in tails if m.group(1).endswith(w)]
        if kin:
            by_sex = tails[kin[0]]
            out_bodies[tile] = ("tile", by_sex.get(m.group(2) or "", first_tail), name)
            continue
        to_pal = palette(cell(tile), range(TS - 4, TS))
        if not (from_pal and to_pal):
            continue
        swap = dict(zip(from_pal, to_pal))
        pic = cell(first_tail)
        for y in range(TS):
            for x in range(TS):
                p = pic.getpixel((x, y))
                if p[3] >= 128 and p[:3] in swap:
                    pic.putpixel((x, y), swap[p[:3]] + (p[3],))
        fname = "nhv_wormbody_%d.png" % tile
        pic.save(os.path.join(TILES, "textures", fname))
        out_bodies[tile] = ("texture", fname, name)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- generated by tools/make_worm_bodies.py: what worms' bodies are made\n")
        f.write("-- of (nhv/worms.lua) - a NetHack tile's picture (the long worm tail's),\n")
        f.write("-- or that recoloured for the worm: tails, by the tail's tile; bodies\n")
        f.write("-- (worms with no tail in NetHack), by the worm's own\n")
        f.write("return {\n")
        for kind, table_ in (("tails", out_tails), ("bodies", out_bodies)):
            f.write("\t%s = {\n" % kind)
            for tile in sorted(table_):
                how, what, name = table_[tile]
                value = ("{tile = %d}" % what) if how == "tile" else ('{texture = "%s"}' % what)
                f.write("\t\t[%d] = %s, -- %s\n" % (tile, value, name))
            f.write("\t},\n")
        f.write("}\n")
    print("wrote", len(out_tails) + len(out_bodies), "worm bodies to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()

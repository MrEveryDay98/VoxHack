"""Glove colours for the fists (game/nethackvoxel/mods/nhv_tiles/glove_colors.lua).

Bare-handed, your fists take the colour of the gloves or gauntlets you wear:
this averages each glove tile's picture in nhv_tiles.png (its coloured
pixels: not the see-through ones nor the near-black outline) into one
colour per NetHack tile number. Run it again after redrawing the gloves.
"""
import os
import re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
TILES = os.path.join(HERE, "..", "game", "nethackvoxel", "mods", "nhv_tiles")
SHEET = os.path.join(TILES, "textures", "nhv_tiles.png")
NAMES = os.path.join(TILES, "tilenames.lua")
OUT = os.path.join(TILES, "glove_colors.lua")
# where a glove covers the fist sprite (white: gloved; see-through: bare):
# made if missing, to the wrist; redraw it for longer gauntlets
MASK = os.path.join(TILES, "textures", "nhv_glove_mask.png")
GLOVE_ROWS = 9
TS = 16


def main():
    src = open(NAMES, encoding="utf-8").read()
    cols = int(re.search(r"cols = (\d+)", src).group(1))
    # tile number -> name, and tile number -> sheet position
    # (the tables by their exact names: "sheet_names" holds "names" too)
    def table(name):
        return src.split("\n  " + name + " = {", 1)[1].split("}", 1)[0]

    names = dict((int(k), v) for k, v in re.findall(r'\[(\d+)\] = "([^"]*)"', table("names")))
    sheet = dict((int(k), int(v)) for k, v in re.findall(r"\[(\d+)\] = (\d+)", table("sheet")))
    im = Image.open(SHEET).convert("RGBA")
    out = {}
    for tile, name in names.items():
        if "glove" not in name and "gauntlet" not in name:
            continue
        s = sheet.get(tile, tile)
        x0, y0 = (s % cols) * TS, (s // cols) * TS
        r = g = b = n = 0
        for y in range(y0, y0 + TS):
            for x in range(x0, x0 + TS):
                pr, pg, pb, pa = im.getpixel((x, y))
                if pa < 128 or pr + pg + pb < 90:
                    continue
                r, g, b, n = r + pr, g + pg, b + pb, n + 1
        if n:
            out[tile] = "#%02X%02X%02X" % (r // n, g // n, b // n)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- generated by tools/make_glove_colors.py: NetHack tile -> the\n")
        f.write("-- gloves' colour (the fists take it, bare-handed)\n")
        f.write("return {\n")
        for tile in sorted(out):
            f.write('\t[%d] = "%s", -- %s\n' % (tile, out[tile], names[tile]))
        f.write("}\n")
    print("wrote", len(out), "glove colours to", os.path.normpath(OUT))
    if not os.path.exists(MASK):
        m = Image.new("RGBA", (TS, TS), (0, 0, 0, 0))
        for y in range(GLOVE_ROWS):
            for x in range(TS):
                m.putpixel((x, y), (255, 255, 255, 255))
        m.save(MASK)
        print("made", os.path.normpath(MASK))


if __name__ == "__main__":
    main()

"""Animated tiles' second frames (game/nethackvoxel/mods/nhv_tiles/anim_frames.lua).

A fountain's water flips from side to side (nhv/mobs.lua): its second
frame is the water (the picture's pure blue) mirrored, behind the rest of
the picture as it is. Three masks/overlays per tile, in textures/, put
together in the game from whichever sheet is in use (nhv_tiles.texture):
 * nhv_anim_<tile>_water.png: where the water is (mirrored in the game)
 * nhv_anim_<tile>_rest.png: where the rest is, drawn over it
 * nhv_anim_<tile>_fix.png: the fountain head's tip, mirrored with the
   water - where the mirrored water would leave a hole in it, the colour
   under it fills it, and the piece of it the water lands behind is left
   out of the rest (no see-through gap at its tip)
Run it again after redrawing the tiles.
"""
import os
import re

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
TILES = os.path.join(HERE, "..", "game", "nethackvoxel", "mods", "nhv_tiles")
SHEET = os.path.join(TILES, "textures", "nhv_tiles.png")
NAMES = os.path.join(TILES, "tilenames.lua")
OUT = os.path.join(TILES, "anim_frames.lua")
TS = 16
ANIMATED = ["fountain"]
WATER = (0, 0, 255)
KEEP, NONE = (255, 255, 255, 255), (0, 0, 0, 0)


def main():
    src = open(NAMES, encoding="utf-8").read()
    cols = int(re.search(r"cols = (\d+)", src).group(1))

    def table(name):
        return src.split("\n  " + name + " = {", 1)[1].split("}", 1)[0]

    names = dict((int(k), v) for k, v in re.findall(r'\[(\d+)\] = "([^"]*)"', table("names")))
    sheet = dict((int(k), int(v)) for k, v in re.findall(r"\[(\d+)\] = (\d+)", table("sheet")))
    im = Image.open(SHEET).convert("RGBA")
    out = {}
    for tile, name in sorted(names.items()):
        if name not in ANIMATED:
            continue
        s = sheet.get(tile, tile)
        x0, y0 = (s % cols) * TS, (s // cols) * TS
        cell = im.crop((x0, y0, x0 + TS, y0 + TS))

        def at(x, y):
            return cell.getpixel((x, y)) if 0 <= x < TS and 0 <= y < TS else NONE

        def solid(x, y):
            return at(x, y)[3] >= 128

        def water(x, y):
            return solid(x, y) and at(x, y)[:3] == WATER

        water_m = Image.new("RGBA", (TS, TS), NONE)
        rest_m = Image.new("RGBA", (TS, TS), NONE)
        fix = Image.new("RGBA", (TS, TS), NONE)
        for y in range(TS):
            for x in range(TS):
                if water(x, y):
                    water_m.putpixel((x, y), KEEP)
                elif solid(x, y):
                    rest_m.putpixel((x, y), KEEP)
        for y in range(TS):
            for x in range(TS):
                m = TS - 1 - x
                # (mirrored, the water lands behind this piece of the
                # picture and leaves a hole across from it: water here, the
                # hole filled with the colour under it - the head's tip)
                if solid(x, y) and not water(x, y) and water(m, y) \
                        and solid(m, y + 1) and not water(m, y + 1):
                    rest_m.putpixel((x, y), NONE)
                    fix.putpixel((m, y), at(m, y + 1))
        base = "nhv_anim_%d_" % tile
        water_m.save(os.path.join(TILES, "textures", base + "water.png"))
        rest_m.save(os.path.join(TILES, "textures", base + "rest.png"))
        fix.save(os.path.join(TILES, "textures", base + "fix.png"))
        out[tile] = (base, name)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- generated by tools/make_anim_frames.py: animated tiles' second frames\n")
        f.write("-- (the water mirrored behind the rest): their masks' names, by tile\n")
        f.write("return {\n")
        for tile in sorted(out):
            base, name = out[tile]
            f.write('\t[%d] = {water = "%swater.png", rest = "%srest.png", fix = "%sfix.png"}, -- %s\n'
                    % (tile, base, base, base, name))
        f.write("}\n")
    print("wrote", len(out), "animated tiles to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()

"""Colours for long worms' voxel tails (game/nethackvoxel/mods/nhv_tiles/worm_colors.lua).

A long worm's tail is drawn as a chain of voxel segments (nhv/worms.lua),
in the worm's own colours: this reads each worm's picture in nhv_tiles.png
- its bottom rows, its body (not its eyes) - and takes its most common
colour for the body, the next for the stripe along its back, and its
darkest for the shading underneath; written for the tail's tile ("long
worm tail,male" from "long worm,male"). Run it again after redrawing
the worms.
"""
import os
import re
from collections import Counter

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
TILES = os.path.join(HERE, "..", "game", "nethackvoxel", "mods", "nhv_tiles")
SHEET = os.path.join(TILES, "textures", "nhv_tiles.png")
NAMES = os.path.join(TILES, "tilenames.lua")
OUT = os.path.join(TILES, "worm_colors.lua")
TS = 16


def hexc(c):
    return "#%02X%02X%02X" % c[:3]


def main():
    src = open(NAMES, encoding="utf-8").read()
    cols = int(re.search(r"cols = (\d+)", src).group(1))

    def table(name):
        return src.split("\n  " + name + " = {", 1)[1].split("}", 1)[0]

    names = dict((int(k), v) for k, v in re.findall(r'\[(\d+)\] = "([^"]*)"', table("names")))
    sheet = dict((int(k), int(v)) for k, v in re.findall(r"\[(\d+)\] = (\d+)", table("sheet")))
    by_name = dict((v, k) for k, v in names.items())
    im = Image.open(SHEET).convert("RGBA")
    out = {}
    for tile, name in names.items():
        m = re.match(r"(.*) tail(,.*)?$", name)
        if not m or name.startswith("statue of") or (m.group(1) + (m.group(2) or "")) not in by_name:
            continue
        worm = by_name[m.group(1) + (m.group(2) or "")]
        s = sheet.get(worm, worm)
        x0, y0 = (s % cols) * TS, (s // cols) * TS
        seen = Counter()
        for y in range(y0 + TS - 4, y0 + TS):
            for x in range(x0, x0 + TS):
                p = im.getpixel((x, y))
                if p[3] >= 128:
                    seen[p[:3]] += 1
        if not seen:
            continue
        dark = min(seen, key=lambda c: sum(c))
        lit = [c for c, _ in seen.most_common() if c != dark]
        body = lit[0] if lit else dark
        accent = lit[1] if len(lit) > 1 else body
        out[tile] = (body, accent, dark, names[worm])
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- generated by tools/make_worm_colors.py: a worm's tail tile -> the\n")
        f.write("-- colours of its voxel segments (the worm's own: body, the stripe\n")
        f.write("-- along its back, the shading underneath)\n")
        f.write("return {\n")
        for tile in sorted(out):
            body, accent, dark, worm = out[tile]
            f.write('\t[%d] = {body = "%s", accent = "%s", dark = "%s"}, -- %s\n'
                    % (tile, hexc(body), hexc(accent), hexc(dark), worm))
        f.write("}\n")
    print("wrote", len(out), "worm colours to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()

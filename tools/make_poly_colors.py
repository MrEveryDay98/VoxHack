"""Polymorphed fists' colours (game/nethackvoxel/mods/nhv_tiles/poly_colors.lua).

Polymorphed and bare-handed, your fist is palette-swapped to the two main
colours of what you've turned into: this finds each monster tile's two
most-used colours in nhv_tiles.png (its coloured pixels: not the see-through
ones nor the near-black outline) - the first takes the fist's skin, the
second its shading (only one colour: a darker one of it for the shading).
It also makes the fist's two masks if they're missing (white where the fist
sprite, nhv_weapon_Fist.png, has its skin colour, and its shading colour).
Run it again after redrawing the monsters or the fist.
"""
import os
import re
from collections import Counter

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
TILES = os.path.join(HERE, "..", "game", "nethackvoxel", "mods", "nhv_tiles")
TEX = os.path.join(TILES, "textures")
SHEET = os.path.join(TEX, "nhv_tiles.png")
NAMES = os.path.join(TILES, "tilenames.lua")
OUT = os.path.join(TILES, "poly_colors.lua")
FIST = os.path.join(TEX, "nhv_weapon_Fist.png")
MASKS = (os.path.join(TEX, "nhv_fist_mask_skin.png"), os.path.join(TEX, "nhv_fist_mask_shade.png"))
TS = 16


def masks():
    if all(os.path.exists(m) for m in MASKS):
        return
    im = Image.open(FIST).convert("RGBA")
    counts = Counter(p[:3] for p in im.getdata() if p[3] >= 128)
    skin, shade = [c for c, _ in counts.most_common(2)]
    for path, col in zip(MASKS, (skin, shade)):
        m = Image.new("RGBA", im.size, (0, 0, 0, 0))
        for y in range(im.height):
            for x in range(im.width):
                p = im.getpixel((x, y))
                if p[3] >= 128 and p[:3] == col:
                    m.putpixel((x, y), (255, 255, 255, 255))
        m.save(path)
        print("made", os.path.normpath(path))


def main():
    masks()
    src = open(NAMES, encoding="utf-8").read()
    cols = int(re.search(r"cols = (\d+)", src).group(1))
    monsters = int(re.search(r"monsters = (\d+)", src).group(1))

    def table(name):
        return src.split("\n  " + name + " = {", 1)[1].split("}", 1)[0]

    names = dict((int(k), v) for k, v in re.findall(r'\[(\d+)\] = "([^"]*)"', table("names")))
    sheet = dict((int(k), int(v)) for k, v in re.findall(r"\[(\d+)\] = (\d+)", table("sheet")))
    im = Image.open(SHEET).convert("RGBA")
    out = {}
    for tile in range(monsters):
        s = sheet.get(tile, tile)
        x0, y0 = (s % cols) * TS, (s // cols) * TS
        counts = Counter()
        for y in range(y0, y0 + TS):
            for x in range(x0, x0 + TS):
                pr, pg, pb, pa = im.getpixel((x, y))
                if pa < 128 or pr + pg + pb < 90:
                    continue
                counts[(pr, pg, pb)] += 1
        top = [c for c, _ in counts.most_common(2)]
        if not top:
            continue
        if len(top) == 1:
            top.append(tuple(int(v * 0.6) for v in top[0]))
        out[tile] = ["#%02X%02X%02X" % c for c in top]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- generated by tools/make_poly_colors.py: NetHack monster tile -> its\n")
        f.write("-- two main colours (a polymorphed hero's fist takes them: skin, shading)\n")
        f.write("return {\n")
        for tile in sorted(out):
            a, b = out[tile]
            f.write('\t[%d] = {"%s", "%s"}, -- %s\n' % (tile, a, b, names.get(tile, "")))
        f.write("}\n")
    print("wrote", len(out), "monster colours to", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
